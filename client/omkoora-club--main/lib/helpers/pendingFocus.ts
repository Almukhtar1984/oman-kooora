// الوصول إلى الطلب نفسه.
//
// «يوديك مباشرة إلى طلب تسجيل اللاعب… ولكن لا تعرف أين مكان الطلب، حتى لو حاولت
// تحديد هذا الطلب لا يظهر. لازم تدور واحد واحد» (العميل، 2026-11-05). الصفحة تعرض
// كل أعضاء النادي صفحةً صفحة، والطلب المعلّق واحد بينهم.
//
// فمن يأتي من «الطلبات» يرى ما عدّه العدّاد وحده، ومن يضغط «تحديد كل قيد الانتظار»
// يرى ما حدّده — وزرٌّ واحد يعيد القائمة كاملة.

export const isUndecided = (row: any) => row?.status === "waiting" || row?.status === "waiting_club";

/** الصفوف التي تخصّها السجلات المطلوبة — وبلا سجلات: القائمة كما هي. */
export const focusOn = <T,>(rows: T[], ids: Set<string> | null, idOf: (row: T) => string | undefined = (row: any) => row?.id): T[] =>
    ids ? rows.filter((row) => ids.has(idOf(row) as string)) : rows;
